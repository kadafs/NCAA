def find_team(name, stats_dict):
    """
    Case-insensitive + partial fuzzy match of team name against stats dict keys.
    Returns (matched_key, stats) or (None, None).
    """
    if not name or not stats_dict:
        return None, None

    original_name = name
    name = TEAM_NAME_OVERRIDES.get(name, name)

    # First try with the override name
    best_key, stats = _fuzzy_match(name, stats_dict)
    if best_key:
        return best_key, stats

    # Fallback to the original name if the override broke the match
    if name != original_name:
        return _fuzzy_match(original_name, stats_dict)
        
    return None, None

def _fuzzy_match(name, stats_dict):
    name_lower = name.lower().strip()

    # Exact match
    if name in stats_dict:
        return name, stats_dict[name]

    # Case-insensitive
    for k in stats_dict:
        if k.lower() == name_lower:
            return k, stats_dict[k]

    # Partial: name contains key or key contains name
    for k in stats_dict:
        k_lower = k.lower()
        if k_lower in name_lower or name_lower in k_lower:
            return k, stats_dict[k]

    # High character overlap via difflib (Safer than single word overlaps)
    import difflib
    best_key, best_score = None, 0.0
    for k in stats_dict:
        similarity = difflib.SequenceMatcher(None, name_lower, k.lower()).ratio()
        if similarity > best_score:
            best_key, best_score = k, similarity
            
    if best_score >= 0.85:
        return best_key, stats_dict[best_key]

    return None, None
    
def global_find_team(name):
    """
    Last resort fallback: Search ALL available bball_stats_*.json files for this team.
    Useful for teams that play in multiple leagues (e.g. Cedevita Olimpija in Slovenia vs ABA).
    """
    search_pattern = "data/bball_stats_*_adv.json"
    files = glob.glob(search_pattern)
    
    # Try exact overrides first
    canonical_name = TEAM_NAME_OVERRIDES.get(name, name)
    
    for fpath in files:
        try:
            with open(fpath, encoding="utf-8") as f:
                data = json.load(f)
                teams = {t["team_name"]: t for t in data.get("teams", [])}
                
                # Try exact canonical
                if canonical_name in teams:
                    return teams[canonical_name], fpath
                
                # Try fuzzy in this file
                best_k, best_s = find_team(name, teams)
                if best_k:
                    return best_s, fpath
        except: continue
        
    return None, None


