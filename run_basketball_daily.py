def calculate_win_prob(spread, std_dev=12.0):
    """Convert a point spread to a win probability using a normal distribution."""
    # probability = norm.cdf(spread / std_dev)
    # Using a simple approximation if scipy is not available, but norm.cdf is better
    return norm.cdf(spread / std_dev)

def predict_game(away_name, home_name, away_id, home_id, team_stats, config, config_path, mode, trace, yesterday_teams=None, ghost_injuries=None):
    """
    Run the UniversalBasketballEngine for a single matchup.
    Returns engine result dict or None if teams not found.
    """
    from core.basketball_engine import UniversalBasketballEngine

    away_key, sA = find_team(away_name, team_stats)
    home_key, sH = find_team(home_name, team_stats)

    # GLOBAL FALLBACK
    if not sA:
        sA, src = global_find_team(away_name)
        if sA:
            sA = dict(sA)
            sA["source"] = f"GLOBAL ({os.path.basename(src)})"
    if not sH:
        sH, src = global_find_team(home_name)
        if sH:
            sH = dict(sH)
            sH["source"] = f"GLOBAL ({os.path.basename(src)})"

    if not sA or not sH:
        missing = []
        if not sA: missing.append(away_name)
        if not sH: missing.append(home_name)
        return None, f"Team stats not found: {', '.join(missing)}"

    # Build game_data in the format the engine expects
    cfg = config
    config_pace = cfg.get("pace_pivot", 76)

    MIN_GAMES_TRUST = 8
    a_gp = sA.get("games_played", sA.get("games", 0))
    h_gp = sH.get("games_played", sH.get("games", 0))

    prev_a = sA.get("previous_season")
    prev_h = sH.get("previous_season")
    a_prev_gp = prev_a.get("games_played", prev_a.get("games", 0)) if prev_a else 0
    h_prev_gp = prev_h.get("games_played", prev_h.get("games", 0)) if prev_h else 0

    # STRICT GUARD: Require either 2+ current games OR a valid prior season baseline (>= 3 games or SRS rating)
    a_has_baseline = (a_gp >= 2) or (prev_a and (a_prev_gp >= 3 or prev_a.get("srs_rating") is not None))
    h_has_baseline = (h_gp >= 2) or (prev_h and (h_prev_gp >= 3 or prev_h.get("srs_rating") is not None))

    if not a_has_baseline or not h_has_baseline:
        return None, f"Insufficient games played & no prior season baseline. {away_name} (curr={a_gp}, prev={a_prev_gp}), {home_name} (curr={h_gp}, prev={h_prev_gp}). Skipping."

    eff_pivot = cfg.get("eff_pivot", 108.0)

    # Dynamic Bayesian & Prior-Season Smoothing
    def smooth_team_ratings(team_s, eff_pivot, config_pace, name):
        gp = team_s.get("games_played", team_s.get("games", 0))
        prev_s = team_s.get("previous_season")
        
        if prev_s and gp < MIN_GAMES_TRUST:
            # Shift smoothly from prior to current over MIN_GAMES_TRUST (8) games
            w_curr = max(0.0, min(1.0, gp / float(MIN_GAMES_TRUST)))
            w_prev = 1.0 - w_curr
            
            raw_off = team_s.get("adj_off", eff_pivot)
            raw_def = team_s.get("adj_def", eff_pivot)
            raw_t   = team_s.get("adj_t", config_pace)
            
            prev_off = prev_s.get("adj_off", eff_pivot)
            prev_def = prev_s.get("adj_def", eff_pivot)
            prev_t   = prev_s.get("adj_t", config_pace)
            
            team_s["adj_off"] = round((raw_off * w_curr) + (prev_off * w_prev), 1)
            team_s["adj_def"] = round((raw_def * w_curr) + (prev_def * w_prev), 1)
            team_s["adj_t"]   = round((raw_t   * w_curr) + (prev_t   * w_prev), 1)
            team_s["prior_blended"] = True
            print(f"    ⭐ PRIOR BLEND: {name} (curr {gp}g, prior {prev_s.get('games_played', prev_s.get('games', '?'))}g) -> Off={team_s['adj_off']}, Def={team_s['adj_def']}, Pace={team_s['adj_t']}")
        elif gp < MIN_GAMES_TRUST:
            # Fallback to standard Bayesian blend toward generic league default
            weight_team = gp / float(MIN_GAMES_TRUST)
            weight_league = 1.0 - weight_team
            team_s["adj_off"] = round((team_s.get("adj_off", eff_pivot) * weight_team) + (eff_pivot * weight_league), 1)
            team_s["adj_def"] = round((team_s.get("adj_def", eff_pivot) * weight_team) + (eff_pivot * weight_league), 1)
            team_s["adj_t"]   = round((team_s.get("adj_t", config_pace) * weight_team) + (config_pace * weight_league), 1)
            print(f"    ⚠ SMALL SAMPLE: {name} ({gp} games) — Bayesian blending toward league average")

    if a_gp < MIN_GAMES_TRUST:
        smooth_team_ratings(sA, eff_pivot, config_pace, away_name)

    if h_gp < MIN_GAMES_TRUST:
        smooth_team_ratings(sH, eff_pivot, config_pace, home_name)

    raw_pace = (sA.get("adj_t", config_pace) + sH.get("adj_t", config_pace)) / 2

    # SANITY CHECK: override adj_t if it deviates wildly from config pace_pivot
    if abs(raw_pace - config_pace) > 20:
        print(f"    ⚠ PACE OVERRIDE: adj_t ({raw_pace:.1f}) deviates from pace_pivot ({config_pace}). Using config value.")
        raw_pace = config_pace

    # FIX 2: KenPom-style crossmatch efficiency for ALL leagues
    lg_avg_eff = cfg.get("eff_pivot", 108.0)
    a_off = sA.get("adj_off", lg_avg_eff)
    a_def = sA.get("adj_def", lg_avg_eff)
    h_off = sH.get("adj_off", lg_avg_eff)
    h_def = sH.get("adj_def", lg_avg_eff)

    # v4.2 Fix: Additive Model (eliminates exponential overshoot)
    a_off_delta = a_off - lg_avg_eff
    h_def_delta = h_def - lg_avg_eff
    h_off_delta = h_off - lg_avg_eff
    a_def_delta = a_def - lg_avg_eff

    exp_a_eff = lg_avg_eff + a_off_delta + h_def_delta
    exp_h_eff = lg_avg_eff + h_off_delta + a_def_delta
    crossmatch_eff = (exp_a_eff + exp_h_eff) / 2

    # FIX 4 (REVISED): Multiplicative KenPom spread perfectly constrained by Game Pace & Home Court Advantage
    raw_spread_eff = exp_h_eff - exp_a_eff
    hca_spread = cfg.get("hca_spread_bump", 2.5) 
    spread_est = (raw_spread_eff * (raw_pace / 100)) + hca_spread

    is_b2b_home = False
    is_b2b_away = False
    if yesterday_teams is not None:
        is_b2b_home = (home_id in yesterday_teams) or (home_name in yesterday_teams)
        is_b2b_away = (away_id in yesterday_teams) or (away_name in yesterday_teams)

    game_data = {
        "team":       away_name,
        "opponent":   home_name,
        "statsA":     sA,
        "statsH":     sH,
        "pace_adjustment":      raw_pace,
        "efficiency_adjustment": crossmatch_eff,
        "projected_spread": abs(spread_est),
        "market_total": None,
        "is_neutral": False,
        "is_b2b_home": is_b2b_home,
        "is_b2b_away": is_b2b_away,
    }

    try:
        engine = UniversalBasketballEngine(config_path, mode=mode)
        engine.trace_enabled = trace
        
        # Merge ghost injuries
        game_injuries = []
        if ghost_injuries:
            game_injuries.extend(ghost_injuries.get(away_name, []))
            game_injuries.extend(ghost_injuries.get(home_name, []))
            
        result = engine.calculate_total(game_data, injury_notes=game_injuries)
        # FIX 4: Spread uses both offense and defense
        spr = spread_est  # Already computed above with crossmatch formula
        model_total = result.get("final_model_total", 0.0)

        # HARD CEILING: Cap non-NBA model totals at 250 as a safety net
        if model_total > 250 and cfg.get("name") != "NBA":
            print(f"    ⚠ CEILING CAP: Inflated projection {model_total:.1f} -> 250.0")
            model_total = 250.0
            result["final_model_total"] = model_total
        
        xpts_h = (model_total / 2) + (spr / 2)
        xpts_a = (model_total / 2) - (spr / 2)
        result["xpts_h"] = round(xpts_h, 1)
        result["xpts_a"] = round(xpts_a, 1)

        # FIX 8: Configurable win probability std_dev
        win_std = cfg.get("win_prob_std_dev", 12.0)
        p_home = calculate_win_prob(spr, std_dev=win_std)
        p_away = 1.0 - p_home
        
        result["probs_1x2"] = {
            "home": round(p_home * 100, 1),
            "away": round(p_away * 100, 1)
        }
        result["predicted_result"] = "HOME" if spr > 0 else "AWAY"
        
        return result, None
    except Exception as e:
        return None, str(e)


